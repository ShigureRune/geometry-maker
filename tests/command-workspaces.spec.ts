import {test,expect} from '@playwright/test';
test('command palette workspaces filter favorites, recent and clear only command history',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('./?legacy-ui=1');
 const seedBefore=await page.getByTestId('current-seed').textContent();
 await page.getByRole('button',{name:'コマンド検索'}).click();
 const dialog=page.getByRole('dialog',{name:'クイックコマンド'});
 const favorites=dialog.getByRole('button',{name:'★ お気に入り',exact:true});
 const recent=dialog.getByRole('button',{name:'最近使った操作'});
 await favorites.click();
 await expect(dialog.getByText('お気に入りはまだありません')).toBeVisible();
 await dialog.getByRole('button',{name:'すべて'}).click();
 const search=dialog.getByRole('searchbox',{name:'コマンドを検索'});
 await search.fill('背景');
 await dialog.getByRole('button',{name:'☆ 選択中をお気に入り'}).click();
 await favorites.click();
 await expect(dialog.locator('.studio-command-result')).toHaveCount(1);
 await expect(dialog.locator('.studio-command-result')).toContainText('背景の設定を開く');
 await search.press('Enter');
 await expect(dialog).toHaveCount(0);
 await page.getByRole('button',{name:'コマンド検索'}).click();
 await recent.click();
 await expect(dialog.locator('.studio-command-result')).toHaveCount(1);
 await dialog.getByRole('button',{name:'最近使った操作の履歴を消去'}).click();
 await expect(dialog.getByText('最近使った操作はまだありません')).toBeVisible();
 await expect(page.getByTestId('current-seed')).toHaveText(seedBefore!);
 await page.reload();
 await page.getByRole('button',{name:'コマンド検索'}).click();
 await recent.click();
 await expect(dialog.getByText('最近使った操作はまだありません')).toBeVisible();
 await favorites.click();
 await expect(dialog.locator('.studio-command-result')).toHaveCount(1);
 expect(errors).toEqual([]);
});
test('iPhone workspace tabs fit without horizontal overflow and preserve keyboard focus',async({page})=>{
 await page.setViewportSize({width:390,height:844});
 await page.goto('./?legacy-ui=1');
 await page.getByRole('button',{name:'コマンド検索'}).click();
 const dialog=page.getByRole('dialog',{name:'クイックコマンド'});
 await dialog.getByRole('button',{name:'最近使った操作'}).click();
 await expect(dialog.getByRole('button',{name:'最近使った操作'})).toHaveAttribute('aria-pressed','true');
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
 await dialog.getByRole('searchbox',{name:'コマンドを検索'}).fill('3D');
 await expect(dialog.locator('.studio-command-result')).toHaveCount(0);
 await dialog.getByRole('button',{name:'すべて'}).click();
 await expect(dialog.locator('.studio-command-result').first()).toBeVisible();
 await dialog.getByRole('searchbox',{name:'コマンドを検索'}).press('Escape');
 await expect(dialog).toHaveCount(0);
});
